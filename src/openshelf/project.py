"""Connect KBs to a project: .openshelf/kbs.yaml, fetching, kbs.lock and context.md."""

from __future__ import annotations

import os
import shutil
import subprocess
import uuid
from pathlib import Path

import yaml

from . import SPEC_VERSION
from .kb import KB, KBError
from .lint import validator

DIR = ".openshelf"
KBS = "kbs.yaml"
LOCK = "kbs.lock"
CONTEXT = "context.md"
CACHE = "cache"


class ProjectError(Exception):
    pass


def find_root(start: str | Path = ".") -> Path:
    """The nearest directory at or above `start` holding .openshelf/kbs.yaml, else `start`."""
    start = Path(start).resolve()
    for d in [start, *start.parents]:
        if (d / DIR / KBS).is_file():
            return d
    return start


def load(root: Path) -> dict:
    path = root / DIR / KBS
    if not path.is_file():
        return {"openshelf": SPEC_VERSION, "kbs": []}
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    errors = [e.message for e in validator("project.schema.json").iter_errors(data)]
    if errors:
        raise ProjectError(f"{path}: " + "; ".join(errors))
    ids = [k["id"] for k in data["kbs"]]
    if len(ids) != len(set(ids)):
        raise ProjectError(f"{path}: duplicate KB ids")
    return data


def save(root: Path, data: dict) -> None:
    (root / DIR).mkdir(parents=True, exist_ok=True)
    (root / DIR / KBS).write_text(yaml.safe_dump(data, sort_keys=False), encoding="utf-8")


def git_url(source: str) -> str | None:
    """The clone URL for a git source, or None for a local path."""
    if source.startswith("github:"):
        return f"https://github.com/{source[len('github:'):]}.git"
    if "://" in source or source.startswith("git@") or source.endswith(".git"):
        return source
    return None


def _git(*args: str, cwd: Path | None = None) -> str:
    result = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True)
    if result.returncode:
        raise ProjectError(f"git {' '.join(args)}: {result.stderr.strip()}")
    return result.stdout.strip()


def _checkout(repo: Path, ref: str | None, commit: str | None) -> str:
    """Check out `commit` if given, else the tip of `ref` (default: remote HEAD)."""
    if commit:
        target = commit
    else:
        candidates = [f"origin/{ref}", ref] if ref else ["origin/HEAD"]
        target = None
        for c in candidates:
            try:
                target = _git("rev-parse", "--verify", "--quiet", f"{c}^{{commit}}", cwd=repo)
                break
            except ProjectError:
                continue
        if target is None:
            raise ProjectError(f"ref '{ref}' not found in {repo}")
    _git("checkout", "--quiet", "--detach", target, cwd=repo)
    return _git("rev-parse", "HEAD", cwd=repo)


def fetch(root: Path, entry: dict, *, offline: bool = False, commit: str | None = None) -> str | None:
    """Make a git KB available in the cache. Returns the checked-out commit."""
    url = git_url(entry["source"])
    if url is None:
        return None
    dest = root / DIR / CACHE / entry["id"]
    if not dest.exists():
        if offline:
            raise ProjectError(f"{entry['id']}: not in cache and --offline was given")
        dest.parent.mkdir(parents=True, exist_ok=True)
        _git("clone", "--quiet", "--no-checkout", url, str(dest))
    elif not offline:
        _git("fetch", "--quiet", "origin", cwd=dest)
    return _checkout(dest, entry.get("ref"), commit)


def kb_root(root: Path, entry: dict) -> Path:
    base = root / DIR / CACHE / entry["id"] if git_url(entry["source"]) else root / entry["source"]
    return (base / entry.get("path", ".")).resolve()


def _relpath(path: Path, root: Path) -> str:
    return Path(os.path.relpath(path, root)).as_posix()


def render_context(root: Path, entries: list[dict], kbs: list[KB]) -> str:
    lines = [
        f"<!-- Generated by openshelf from {DIR}/{KBS}; do not edit. Paths are relative to the project root. -->",
        "# Connected knowledge bases",
        "",
        "Read a KB's index only when the task falls within its scope, then open only the pages you need.",
        "A link `kb://<kb-id>/<page-id>` means the file `<page-id>.md` under that KB's pages directory.",
    ]
    for entry, kb in zip(entries, kbs):
        lines += ["", f"## {kb.id} — {kb.title}", kb.description]
        if entry.get("use"):
            lines.append(f"- Use: {entry['use']}")
        lines.append(f"- Index: {_relpath(kb.path('index'), root)}")
        lines.append(f"- Pages: {_relpath(kb.path('pages'), root)}/")
    return "\n".join(lines) + "\n"


def sync(root: Path, *, offline: bool = False, locked: bool = False) -> list[KB]:
    """Fetch every KB, check it, and write kbs.lock and context.md."""
    data = load(root)
    lock_path = root / DIR / LOCK
    lock = (yaml.safe_load(lock_path.read_text(encoding="utf-8")) or {}) if lock_path.is_file() else {}
    locked_kbs = lock.get("kbs") or {}
    new_lock: dict = {}
    kbs = []
    for entry in data["kbs"]:
        pinned = locked_kbs.get(entry["id"], {}).get("commit") if locked else None
        if locked and git_url(entry["source"]) and not pinned:
            raise ProjectError(f"{entry['id']}: not in {LOCK}; run sync without --locked first")
        commit = fetch(root, entry, offline=offline, commit=pinned)
        try:
            kb = KB(kb_root(root, entry))
        except KBError as e:
            raise ProjectError(f"{entry['id']}: {e}") from e
        if kb.id != entry["id"]:
            raise ProjectError(f"{entry['id']}: the KB's own id is '{kb.id}'")
        kbs.append(kb)
        new_lock[entry["id"]] = {"source": entry["source"], **({"commit": commit} if commit else {})}

    (root / DIR).mkdir(parents=True, exist_ok=True)
    lock_path.write_text(yaml.safe_dump({"openshelf": SPEC_VERSION, "kbs": new_lock}, sort_keys=False), encoding="utf-8")
    (root / DIR / CONTEXT).write_text(render_context(root, data["kbs"], kbs), encoding="utf-8")
    gitignore = root / DIR / ".gitignore"
    if not gitignore.is_file() or f"{CACHE}/" not in gitignore.read_text(encoding="utf-8").split():
        with gitignore.open("a", encoding="utf-8") as f:
            f.write(f"{CACHE}/\n")
    return kbs


def add(root: Path, source: str, *, id: str | None = None, ref: str | None = None,
        path: str | None = None, use: str | None = None) -> dict:
    """Add a KB to the project, reading its id from its manifest if not given."""
    data = load(root)
    entry = {"id": id or "", "source": source}
    if ref:
        entry["ref"] = ref
    if path:
        entry["path"] = path
    if use:
        entry["use"] = use

    if not id:
        if git_url(source):
            tmp = f".tmp-{uuid.uuid4().hex[:8]}"
            try:
                fetch(root, {**entry, "id": tmp})
                entry["id"] = KB(kb_root(root, {**entry, "id": tmp})).id
            except KBError as e:
                raise ProjectError(str(e)) from e
            finally:
                cached = root / DIR / CACHE / tmp
                if cached.exists() and entry["id"] and not (root / DIR / CACHE / entry["id"]).exists():
                    cached.rename(root / DIR / CACHE / entry["id"])
                elif cached.exists():
                    shutil.rmtree(cached)
        else:
            try:
                entry["id"] = KB(kb_root(root, {**entry, "id": "_"})).id
            except KBError as e:
                raise ProjectError(str(e)) from e
    if any(k["id"] == entry["id"] for k in data["kbs"]):
        raise ProjectError(f"a KB with id '{entry['id']}' is already connected")
    data["kbs"].append(entry)
    errors = [e.message for e in validator("project.schema.json").iter_errors(data)]
    if errors:
        raise ProjectError("; ".join(errors))
    save(root, data)
    return entry
